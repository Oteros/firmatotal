export function resolveLocale() {
  const query = new URLSearchParams(location.search).get('lang')
  if (languages.some((language) => language.code === query)) return query
  const saved = localStorage.getItem('firma-total-language')
  if (languages.some((language) => language.code === saved)) return saved
  const preferences = navigator.languages?.length ? navigator.languages : [navigator.language]
  for (const preference of preferences) {
    const normalized = String(preference).toLowerCase()
    const match = languages.find((language) => normalized === language.code || normalized.startsWith(`${language.code}-`))
    if (match) return match.code
  }
  return 'en'
}

export function createTranslator(locale) {
  const dictionary = dictionaries[locale] || dictionaries.en
  return (key) => dictionary[key]
    ?? safetyMessages[locale]?.[key]
    ?? dictionaries.en[key]
    ?? safetyMessages.en[key]
    ?? key
}
